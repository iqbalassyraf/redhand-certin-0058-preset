/* Minimal asciicast player: no network, no dependencies. Reads window.CRAFTY_FALCON_CAST,
   an array of [seconds, "o", text] events generated by scripts/build_docs.py. */
(function () {
  "use strict";
  var cast = window.CRAFTY_FALCON_CAST;
  var root = document.getElementById("player");
  if (!cast || !root) return;

  var COLORS = ["#6e7681", "#ff7b72", "#3fb950", "#d29922", "#58a6ff", "#bc8cff", "#39c5cf", "#e6edf3"];
  var term = root.querySelector(".term");
  var btn = root.querySelector("[data-play]");
  var restart = root.querySelector("[data-restart]");
  var speedSel = root.querySelector("[data-speed]");
  var seek = root.querySelector("[data-seek]");
  var clock = root.querySelector("[data-clock]");
  var total = cast.length ? cast[cast.length - 1][0] : 0;
  seek.max = String(Math.ceil(total * 100));

  function esc(s) {
    return s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
  }

  function toHtml(text) {
    text = text.replace(/\r\n/g, "\n").replace(/\r/g, "");
    var st = { b: false, d: false, i: false, fg: null, bg: null };
    var re = /\x1b\[([0-9;]*)m/g;
    var out = "";
    var last = 0;
    var m;
    function emit(s) {
      if (!s) return;
      var css = [];
      if (st.fg !== null) css.push("color:" + COLORS[st.fg]);
      if (st.bg !== null) css.push("background:" + COLORS[st.bg]);
      if (st.b) css.push("font-weight:700");
      if (st.d) css.push("opacity:.6");
      if (st.i) css.push("font-style:italic");
      out += css.length ? '<span style="' + css.join(";") + '">' + esc(s) + "</span>" : esc(s);
    }
    while ((m = re.exec(text)) !== null) {
      emit(text.slice(last, m.index));
      last = re.lastIndex;
      var codes = m[1] === "" ? [0] : m[1].split(";").map(Number);
      for (var k = 0; k < codes.length; k++) {
        var c = codes[k];
        if (c === 0) st = { b: false, d: false, i: false, fg: null, bg: null };
        else if (c === 1) st.b = true;
        else if (c === 2) st.d = true;
        else if (c === 3) st.i = true;
        else if (c === 22) { st.b = false; st.d = false; }
        else if (c === 23) st.i = false;
        else if (c >= 30 && c <= 37) st.fg = c - 30;
        else if (c === 39) st.fg = null;
        else if (c >= 40 && c <= 47) st.bg = c - 40;
        else if (c === 49) st.bg = null;
      }
    }
    emit(text.slice(last));
    return out;
  }

  var pos = 0; // current playback time in seconds
  var shown = -1; // number of events currently rendered
  var playing = false;
  var wallStart = 0;
  var posStart = 0;

  function render(t) {
    var n = 0;
    while (n < cast.length && cast[n][0] <= t) n++;
    if (n !== shown) {
      var text = "";
      for (var i = 0; i < n; i++) text += cast[i][2];
      term.innerHTML = n ? toHtml(text) : "";
      term.scrollTop = term.scrollHeight;
      shown = n;
    }
    seek.value = String(Math.round(t * 100));
    clock.textContent = t.toFixed(1) + " / " + total.toFixed(1) + " s";
  }

  function speed() {
    return Number(speedSel.value) || 1;
  }

  function tick(now) {
    if (!playing) return;
    pos = Math.min(total, posStart + ((now - wallStart) / 1000) * speed());
    render(pos);
    if (pos >= total) return stop();
    window.requestAnimationFrame(tick);
  }

  function play() {
    if (pos >= total) pos = 0;
    playing = true;
    btn.textContent = "Pause";
    posStart = pos;
    wallStart = performance.now();
    window.requestAnimationFrame(tick);
  }

  function stop() {
    playing = false;
    btn.textContent = pos >= total ? "Replay" : "Play";
  }

  btn.addEventListener("click", function () {
    if (playing) stop();
    else play();
  });
  restart.addEventListener("click", function () {
    stop();
    pos = 0;
    shown = -1;
    render(0);
    play();
  });
  speedSel.addEventListener("change", function () {
    if (playing) {
      posStart = pos;
      wallStart = performance.now();
    }
  });
  seek.addEventListener("input", function () {
    pos = Number(seek.value) / 100;
    posStart = pos;
    wallStart = performance.now();
    render(pos);
    if (!playing) btn.textContent = pos >= total ? "Replay" : "Play";
  });

  term.setAttribute("data-ready", "1");
  render(0);
})();
