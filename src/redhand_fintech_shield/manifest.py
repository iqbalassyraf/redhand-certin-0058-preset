"""A machine-readable description of the preset, for a host application to consume.

``get_manifest()`` is registered as a ``redhand.presets`` entry point, so a host can discover the
installed presets without importing anything else, read what each one enforces, and check its
version and fingerprint.
"""

from __future__ import annotations

from typing import Literal

from pydantic import BaseModel, ConfigDict

from . import protocols
from .rules import RULE_CATALOG

_STRICT = ConfigDict(frozen=True, extra="forbid")


class Advisory(BaseModel):
    model_config = _STRICT

    id: str
    title: str


class RuleEntry(BaseModel):
    model_config = _STRICT

    id: str
    name: str
    stage: int
    severity: Literal["low", "medium", "high", "critical"]
    decision: Literal["block", "hitl_required", "allow", "varies"]
    advisories: tuple[str, ...]
    summary: str
    rationale: str
    overridable: bool
    exemptible: bool


class ExtensionPoint(BaseModel):
    model_config = _STRICT

    name: str
    summary: str


class PresetManifest(BaseModel):
    """What this preset is, which advisories it maps to, and what it enforces."""

    model_config = _STRICT

    manifest_version: int = 1
    preset_id: str
    preset_version: str
    schema_version: int
    package_version: str
    policy_sha256: str
    advisories: tuple[Advisory, ...]
    rules: tuple[RuleEntry, ...]
    extension_points: tuple[ExtensionPoint, ...]


# Maps to the published advisories only; no certification or compliance claim is made.
ADVISORIES = (
    Advisory(id="CIAD-2026-0058", title="CRAFTY FALCON"),
    Advisory(id="CIAD-2026-0049", title="AI Agents as Attack Vectors"),
)


def extension_points() -> tuple[ExtensionPoint, ...]:
    """Every typing.Protocol in ``protocols``: the seams a host application can fill."""
    found = [
        ExtensionPoint(name=name, summary=((obj.__doc__ or "").strip().splitlines() or [""])[0])
        for name, obj in vars(protocols).items()
        if isinstance(obj, type) and getattr(obj, "_is_protocol", False) and name != "Protocol"
    ]
    return tuple(sorted(found, key=lambda e: e.name))


def get_manifest() -> PresetManifest:
    """Manifest of the bundled preset (the ``redhand.presets`` entry point)."""
    from . import __version__, load_policy

    policy = load_policy()
    return PresetManifest(
        preset_id=policy.preset_id,
        preset_version=policy.preset_version or "unversioned",
        schema_version=policy.schema_version,
        package_version=__version__,
        policy_sha256=policy.fingerprint(),
        advisories=ADVISORIES,
        rules=tuple(
            RuleEntry(
                id=r.id,
                name=r.name,
                stage=r.stage,
                severity=r.severity,
                decision=r.decision,
                advisories=r.advisories,
                summary=r.summary,
                rationale=r.rationale,
                overridable=r.overridable,
                exemptible=r.exemptible,
            )
            for r in RULE_CATALOG
        ),
        extension_points=extension_points(),
    )


def render_rules_markdown(manifest: PresetManifest) -> str:
    """The rule catalog as a Markdown document (committed as ``docs/rules.md``)."""
    lines = [
        "# Rule catalog",
        "",
        "<!-- Generated by `redhand-shield manifest --markdown`; do not edit by hand. -->",
        "",
        f"Preset `{manifest.preset_id}` {manifest.preset_version}, policy schema "
        f"{manifest.schema_version}. Maps to "
        + ", ".join(f"{a.id} ({a.title})" for a in manifest.advisories)
        + ". It maps to these advisories; it does not certify compliance.",
        "",
        "| Rule | Stage | Severity | Decision | Advisory | Tunable | Waivable |",
        "| :--- | :---: | :---: | :---: | :--- | :---: | :---: |",
    ]
    for r in manifest.rules:
        lines.append(
            f"| `{r.id}` | {r.stage} | {r.severity} | {r.decision} | {'; '.join(r.advisories)} | "
            f"{'yes' if r.overridable else 'no'} | {'yes' if r.exemptible else 'no'} |"
        )
    lines += ["", "## Rationale", ""]
    for r in manifest.rules:
        lines += [f"### `{r.id}`", "", f"{r.summary} {r.rationale}", ""]
    lines += [
        "*Tunable*: a policy may run the rule in shadow, disable it or re-label it. "
        "*Waivable*: a time-limited exemption may waive a `hitl_required` violation of it.",
        "",
    ]
    return "\n".join(lines)
